param(
    [Parameter(Mandatory = $true)]
    [string]$ProjectDir,

    # Cache de NuGet, que MSBuild pasa como $(NuGetPackageRoot). Es donde queda
    # gitversion.exe desde que el proyecto usa PackageReference en vez de packages.config.
    [string]$NuGetPackageRoot
)

$ProjectDir = $ProjectDir.Trim().TrimEnd('\', '"')
$outputPath = Join-Path $ProjectDir "Properties\AssemblyInfo.Generated.cs"

# Repo root: git is authoritative, falling back to two levels up (source\Time.Tracking.Jira)
$repoRoot = & git -C $ProjectDir rev-parse --show-toplevel 2>$null
if ($LASTEXITCODE -ne 0 -or -not $repoRoot) {
    $repoRoot = (Resolve-Path (Join-Path $ProjectDir "..\..")).Path
}

# Candidatos a gitversion.exe, en orden de preferencia: la herramienta global primero y
# despues las copias del paquete NuGet.
#
# El paquete trae un tools\<tfm> por cada framework soportado (net8.0, net9.0, net10.0) y
# solo corre el que coincide con un runtime instalado en la maquina. Por eso no alcanza con
# elegir uno: se devuelven todos, del TFM mas nuevo al mas viejo, y el llamador prueba en
# orden hasta que alguno responda.
function Get-GitVersionCandidates {
    $candidates = @()

    $global = Get-Command dotnet-gitversion -ErrorAction SilentlyContinue
    if ($global) { $candidates += $global.Source }

    $roots = @(
        (Join-Path $ProjectDir "packages"),
        (Join-Path $repoRoot "packages")
    )
    if ($NuGetPackageRoot) {
        $roots += (Join-Path $NuGetPackageRoot.Trim().TrimEnd('\', '"') "gitversion.msbuild")
    }

    foreach ($root in $roots) {
        if (-not (Test-Path $root)) { continue }

        $found = Get-ChildItem $root -Filter "gitversion.exe" -Recurse -ErrorAction SilentlyContinue |
                 Sort-Object {
                     # Ordena por numero de TFM, no alfabeticamente: "net9.0" > "net10.0" como
                     # texto, y net10.0 es justamente el que hay que preferir.
                     $tfm = Split-Path (Split-Path $_.FullName -Parent) -Leaf
                     if ($tfm -match '^net(\d+)\.(\d+)$') {
                         [version]("{0}.{1}" -f $Matches[1], $Matches[2])
                     }
                     else { [version]"0.0" }
                 } -Descending

        $candidates += $found | ForEach-Object { $_.FullName }
    }

    return $candidates
}

$json = $null
foreach ($gitVersion in Get-GitVersionCandidates) {
    try {
        $output = & $gitVersion $repoRoot /output json /nofetch 2>$null
        if ($LASTEXITCODE -eq 0 -and $output) {
            $json = $output | ConvertFrom-Json
            if ($json) { break }
        }
    }
    catch {
        $json = $null
    }
}

if (-not $json) {
    # Never replace a known good version with a placeholder: the installer takes its
    # version from the executable, and 0.0.0 would break update detection.
    if (Test-Path $outputPath) {
        Write-Warning "GitVersion no disponible. Se mantiene la version actual de AssemblyInfo.Generated.cs."
        exit 0
    }

    Write-Warning "GitVersion no disponible y no existe AssemblyInfo.Generated.cs. Usando 0.0.0."
    $json = [PSCustomObject]@{
        MajorMinorPatch      = "0.0.0"
        AssemblySemVer       = "0.0.0.0"
        AssemblySemFileVer   = "0.0.0.0"
        InformationalVersion = "0.0.0"
    }
}

$content = @"
// <auto-generated>
// This file is auto-generated by Build\UpdateAssemblyVersion.ps1 using GitVersion.
// Do not edit manually.
// </auto-generated>
using System.Reflection;
[assembly: AssemblyVersion("$($json.AssemblySemVer)")]
[assembly: AssemblyFileVersion("$($json.AssemblySemFileVer)")]
[assembly: AssemblyInformationalVersion("$($json.InformationalVersion)")]
"@

Set-Content -Path $outputPath -Value $content -Encoding UTF8
Write-Host "GitVersion: $($json.MajorMinorPatch) -> $outputPath"
